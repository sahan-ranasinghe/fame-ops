// The mobile website's routes (Phase 8, O4): one small file under src/web-app/office for every screen of Office mode
// (src/app/office), re-exporting it, so the web build has Office mode's screens and nothing of the driver's side.
//
//   node scripts/make-web-routes.mjs           write them (and remove those whose screen is gone)
//   node scripts/make-web-routes.mjs --check   exit 1 when one is missing, extra or stale (npm run test:web-routes)
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, 'src', 'app', 'office');
const to = join(root, 'src', 'web-app', 'office');
const check = process.argv.includes('--check');

const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));
const screens = walk(from).filter((f) => /\.tsx?$/.test(f)).map((f) => relative(from, f));
const body = (rel) => {
  const mod = `@/app/office/${rel.replace(/\\/g, '/').replace(/\.tsx?$/, '')}`;
  return `// Generated by scripts/make-web-routes.mjs: the web build's route for src/app/office/${rel.replace(/\\/g, '/')}. Do not edit.\nexport { default } from '${mod}';\nexport * from '${mod}';\n`;
};

const problems = [];
for (const rel of screens) {
  const target = join(to, rel);
  const want = body(rel);
  if (existsSync(target) && readFileSync(target, 'utf8') === want) continue;
  if (check) problems.push(`missing or stale: ${rel}`);
  else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, want);
  }
}
if (existsSync(to)) {
  for (const extra of walk(to).map((f) => relative(to, f)).filter((rel) => !screens.includes(rel))) {
    if (check) problems.push(`extra: ${extra}`);
    else rmSync(join(to, extra));
  }
}
// Round 4–7, item 12: the design pages of src/design (a screen of the driver app drawn with sample data, for the mockup
// comparison's screenshots) get a route under src/web-app/design ONLY in the e2e build (FLEET_DESIGN=1,
// scripts/test-office-local.sh); every other run removes them, so a deployed build never has one (deploy-pages.sh checks
// too). Not in git (.gitignore). Each design page renders the marker "fleet-design-page" (the deploy's scan looks for it).
const designFrom = join(root, 'src', 'design');
const designTo = join(root, 'src', 'web-app', 'design');
if (!check) {
  rmSync(designTo, { recursive: true, force: true });
  if (process.env.FLEET_DESIGN === '1' && existsSync(designFrom)) {
    mkdirSync(designTo, { recursive: true });
    for (const f of readdirSync(designFrom).filter((n) => /\.tsx$/.test(n))) {
      const name = f.replace(/\.tsx$/, '').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
      writeFileSync(join(designTo, `${name}.tsx`),
        `// Generated by scripts/make-web-routes.mjs with FLEET_DESIGN=1 (the e2e build only). Do not edit.\nexport { default } from '@/design/${f.replace(/\.tsx$/, '')}';\n`);
    }
  }
}

if (check) {
  if (problems.length) {
    console.log(problems.join('\n'));
    console.log(`\n${problems.length} web route(s) out of step: run node scripts/make-web-routes.mjs`);
    process.exit(1);
  }
  console.log(`All ${screens.length} Office mode screens have their web route.`);
} else console.log(`${screens.length} web routes written.`);
